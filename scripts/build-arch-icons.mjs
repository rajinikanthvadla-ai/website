/**
 * Rebuild src/lib/architecture-icons.ts from simple-icons + custom marks.
 * Usage: node scripts/build-arch-icons.mjs
 */
import fs from "node:fs";
import * as si from "simple-icons";

const slugs = [
  "postgresql", "snowflake", "apachekafka", "apacheairflow", "apachespark", "redis",
  "mlflow", "ray", "kubernetes", "nvidia", "githubactions", "docker", "argo", "nginx",
  "prometheus", "grafana", "terraform", "googlecloud", "langchain", "huggingface",
  "anthropic", "googlegemini", "fastapi", "nextdotjs", "react", "opentelemetry",
  "github", "jira", "crewai", "langgraph", "vllm", "python", "ollama",
];

const bySlug = new Map();
for (const icon of Object.values(si)) {
  if (icon?.slug && icon?.path) bySlug.set(icon.slug, icon);
}

const out = {};
for (const slug of slugs) {
  const icon = bySlug.get(slug);
  if (!icon) {
    console.warn("missing simple-icons slug:", slug);
    continue;
  }
  out[slug] = { title: icon.title, hex: icon.hex, path: icon.path };
}

const custom = JSON.parse(fs.readFileSync(new URL("./arch-icons-custom.json", import.meta.url), "utf8"));
Object.assign(out, custom);

const file = `/** Brand icons for architecture diagrams (Simple Icons + custom). Regenerated by scripts/build-arch-icons.mjs */
export type ArchIcon = { title: string; hex: string; path: string };
export const ARCH_ICONS: Record<string, ArchIcon> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync("src/lib/architecture-icons.ts", file);
console.log(`Wrote ${Object.keys(out).length} icons`);
